/**
 * Vendors the webfonts into `public/fonts/` so the site serves them itself.
 *
 * Hotlinking Google Fonts costs two extra connections on the critical path and
 * discloses every visitor's IP to a third party — awkward for a product whose
 * pitch is "100% browser-local, GDPR & PIPL aware". Re-run this script to
 * refresh the files:  node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = resolve(ROOT, 'public/fonts')
const CSS_OUT = resolve(ROOT, 'src/fonts.css')

// Latin only: the UI's CJK text falls back to the system stack, which ships
// far better Chinese glyphs than any subset we could bundle.
const SUBSETS = new Set(['latin', 'latin-ext'])

const SOURCE =
  'https://fonts.googleapis.com/css2' +
  '?family=Inter:wght@400..700' +
  '&family=JetBrains+Mono:wght@400..600' +
  '&display=swap'

// Google serves woff2 only to browsers that advertise support.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

const slug = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, '-')

const response = await fetch(SOURCE, { headers: { 'User-Agent': UA } })
if (!response.ok) throw new Error(`Google Fonts responded ${response.status}`)
const css = await response.text()

const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)]
if (blocks.length === 0) throw new Error('No @font-face blocks found in the stylesheet')

await mkdir(OUT_DIR, { recursive: true })

const rules = []
for (const [, subset, block] of blocks) {
  if (!SUBSETS.has(subset)) continue

  const family = /font-family: '([^']+)'/.exec(block)[1]
  const weight = /font-weight: ([^;]+)/.exec(block)[1].trim()
  const range = /unicode-range: ([^;]+)/.exec(block)[1].trim()
  const url = /url\((https:\/\/[^)]+)\)/.exec(block)[1]

  const file = `${slug(family)}-${subset}.woff2`
  const font = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!font.ok) throw new Error(`${file} responded ${font.status}`)
  const bytes = Buffer.from(await font.arrayBuffer())
  await writeFile(resolve(OUT_DIR, file), bytes)
  console.log(`${file.padEnd(28)} ${(bytes.length / 1024).toFixed(1)} kB`)

  rules.push(
    `@font-face {\n` +
      `  font-family: '${family}';\n` +
      `  font-style: normal;\n` +
      `  font-weight: ${weight};\n` +
      `  font-display: swap;\n` +
      `  src: url('/fonts/${file}') format('woff2');\n` +
      `  unicode-range: ${range};\n` +
      `}`,
  )
}

await writeFile(
  CSS_OUT,
  `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n\n${rules.join('\n\n')}\n`,
)
console.log(`\nWrote ${rules.length} @font-face rules to src/fonts.css`)
